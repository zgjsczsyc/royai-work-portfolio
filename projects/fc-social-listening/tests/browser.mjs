import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Store } from '../lib/store.mjs';
import { seedDemo } from '../lib/demo.mjs';
import { createServer } from '../server.mjs';
const demo = new Store('demo', ':memory:'), real = new Store('real', ':memory:');
seedDemo(demo);
const failed = real.beginRun();
real.addSource(failed.id, { platform: 'weibo', method: 'browser', status: 'needs_login', count: 0, notes: ['测试登录失效'], query: '足球世界' });
real.finishRun(failed.id, { status: 'failed', count: 0 });
const servers = [createServer(demo), createServer(real)];
await Promise.all(servers.map(s => new Promise(resolve => s.listen(0, '127.0.0.1', resolve))));
const base = `http://127.0.0.1:${servers[0].address().port}`, realBase = `http://127.0.0.1:${servers[1].address().port}`;
const output = fileURLToPath(new URL('../test-results/', import.meta.url)); mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
const failures = [], external = [], checks = [];
page.on('pageerror', e => failures.push(e.message));
page.on('request', req => { if (new URL(req.url()).protocol.startsWith('http') && new URL(req.url()).hostname !== '127.0.0.1') external.push(req.url()); });
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); };
try {
  await page.goto(base); await page.getByRole('heading', { name: '今日观察.' }).waitFor();
  await page.waitForFunction(() => document.querySelectorAll('.focus-item').length === 3);
  check('Overview contains 12 event count and synthetic label', (await page.locator('.kpi').first().innerText()).includes('12') && await page.locator('.mode-badge').innerText() === '合成演示');
  await page.waitForTimeout(450); await page.screenshot({ path: output + 'overview-desktop.png', fullPage: true });
  await page.getByRole('button', { name: '事件中心' }).click();
  check('FC focus contains explicitly relevant events', await page.locator('.event-row').count() === 9);
  await page.getByRole('tab', { name: '热门新游', exact: true }).click();
  check('New game filter has 3 events', await page.locator('.event-row').count() === 3);
  await page.getByRole('tab', { name: '电竞赛事', exact: true }).click();
  check('Esports filter has 3 events', await page.locator('.event-row').count() === 3);
  await page.getByRole('tab', { name: '全部行业', exact: true }).click();
  check('All industry includes low-relevance events', await page.locator('.event-row').count() === 12);
  await page.getByRole('textbox', { name: '搜索事件' }).fill('深海回声');
  check('Search narrows result', await page.locator('.event-row').count() === 1);
  await page.getByRole('combobox', { name: '关联度筛选' }).selectOption('75');
  check('Score filtering hides low-relevance result', await page.locator('.event-row').count() === 0);
  await page.getByRole('combobox', { name: '关联度筛选' }).selectOption('0');
  await page.locator('.event-row').click();
  check('Detail shows launch stage and date', (await page.locator('.entity-meta').innerText()).includes('已上线'));
  check('Detail includes 5 quotes', await page.locator('.evidence-card').count() === 5);
  check('Synthetic evidence has no invented live links', await page.locator('.evidence-top a').count() === 0);
  await page.screenshot({ path: output + 'event-detail.png', fullPage: true });
  await page.reload(); await page.locator('.detail-header').waitFor();
  check('Hash route survives reload', (await page.locator('.detail-header h2').innerText()).includes('深海回声'));
  await page.getByRole('button', { name: '本次简报', exact: true }).click();
  check('Report includes new games and esports', (await page.locator('.report-paper').innerText()).includes('热门新游') && (await page.locator('.report-paper').innerText()).includes('电竞动态'));
  for (const [label, extension] of [['下载 Markdown ↓', 'md'], ['下载 HTML ↓', 'html']]) {
    const downloadPromise = page.waitForEvent('download'); await page.getByRole('link', { name: label }).click();
    const download = await downloadPromise; check(`Export ${extension} downloads`, download.suggestedFilename().endsWith('.' + extension));
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '今日概览', exact: true }).click();
  await page.waitForTimeout(400);
  check('Mobile overview has no page overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: output + 'overview-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '事件中心' }).click();
  check('Mobile events use internal table scrolling', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: output + 'events-mobile.png', fullPage: true });
  await page.goto(realBase); await page.locator('.empty').waitFor();
  check('Real empty mode does not load demo content', await page.locator('.mode-badge').innerText() === '真实数据' && !(await page.locator('body').innerText()).includes('星港旅人'));
  check('Login failures are visible', (await page.locator('.platform-grid').innerText()).includes('需要登录'));
  check('No browser runtime errors', failures.length === 0); check('No external requests in dashboard', external.length === 0);
  writeFileSync(output + 'browser-validation.json', JSON.stringify({ passed: checks.length, checks, failures, external }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, failures, screenshots: output }, null, 2));
} finally { await browser.close(); await Promise.all(servers.map(s => new Promise(resolve => s.close(resolve)))); demo.close(); real.close(); }
